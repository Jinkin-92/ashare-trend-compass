def main():
    with open(ROOT / "web/data/symbols.json", encoding="utf-8") as f:
        data = json.load(f)
    rows = {r["symbol_id"]: r for r in data["rows"]}

    print(f"{'分组':<10} {'校准图名称':<10} {'校准温度':<5} {'校准涨幅':<8} {'校准RS':<6} {'本项目ID':<11} {'本项目温度':<8} {'本项目涨幅':<10} {'本项目RS':<6}")
    print("-" * 110)

    match_count = 0
    diff_count = 0
    for group, name, ctemp, cpct, crs, sid in CALIB:
        r = rows.get(sid)
        if not r:
            print(f"{group:<10} {name:<10} {ctemp:<5} {cpct:<8} {crs:<6} {sid:<11} <NOT FOUND>")
            continue
        mtemp = r.get("temperature") or "-"
        mpct = r.get("pct_chg")
        mrs = r.get("rs_score")
        mpct_str = f"{mpct:+.2f}%" if mpct is not None else "-"
        mrs_str = str(mrs) if mrs is not None else "-"
        # 标注差异（温度档位不一致 或 RS 差异 > 15）
        flag = ""
        if mtemp != ctemp:
            flag = " ⚠温度差"
            diff_count += 1
        elif mrs is not None and abs(mrs - crs) > 15:
            flag = " ⚠RS差"
            diff_count += 1
        else:
            match_count += 1
        print(f"{group:<10} {name:<10} {ctemp:<5} {cpct:<8} {crs:<6} {sid:<11} {mtemp:<8} {mpct_str:<10} {mrs_str:<6}{flag}")
    print("-" * 110)
    print(f"\n汇总：{len(CALIB)} 行校准图 → {match_count} 行匹配，{diff_count} 行差异显著")


if __name__ == "__main__":
    main()